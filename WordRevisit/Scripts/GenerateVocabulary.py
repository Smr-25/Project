#!/usr/bin/env python3
"""Rebuild the starter vocabulary and reviewed synonym catalogue. No network required."""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def normalize(value):
    return ' '.join(value.lower().split())

def merge(left, right):
    result, seen = [], set()
    for item in (left + ';' + right).split(';'):
        item = item.strip()
        if item and normalize(item) not in seen:
            result.append(item)
            seen.add(normalize(item))
    return '; '.join(result)

def quoted(value):
    # JSON string escapes are also Swift string escapes for this vocabulary.
    assert '\\' not in value and '\n' not in value
    return json.dumps(value, ensure_ascii=False)

rows = list(csv.DictReader((ROOT / 'Data/SourceVocabulary-v2.csv').open(encoding='utf-8-sig')))
words = {}
legacy = set()
for row in rows:
    key = normalize(row['English'])
    assert key and row['Azerbaijani'].strip()
    if key not in words:
        words[key] = dict(English=row['English'].strip(), Azerbaijani='', Group='')
    words[key]['Azerbaijani'] = merge(words[key]['Azerbaijani'], row['Azerbaijani'])
    legacy.update(normalize(g) for g in row['Group'].split(';') if g.strip())
families = json.loads((ROOT / 'Data/SynonymFamilies.json').read_text())
assert len({f['Code'] for f in families}) == len(families)
for family in families:
    assert family['Terms'][0] == family['Head'] and len(set(family['Terms'])) == len(family['Terms']) >= 2
    for term in family['Terms']:
        assert term in words, term
        words[term]['Group'] = merge(words[term]['Group'], family['Code'])
assert len(words) == 513
with (ROOT / 'Data/Vocabulary.csv').open('w', encoding='utf-8', newline='') as output:
    writer = csv.DictWriter(output, fieldnames=['English', 'Azerbaijani', 'Group'], lineterminator='\n')
    writer.writeheader()
    writer.writerows(words.values())
source = '// Generated by Scripts/GenerateVocabulary.py. Edit the source CSV and family catalogue.\nimport Foundation\n\nenum StarterVocabulary {\n    static let Entries: [WordEntry] = [\n'
for word in words.values():
    source += f'        WordEntry(Term: {quoted(word["English"])}, Translation: {quoted(word["Azerbaijani"])}, Group: {quoted(word["Group"])}),\n'
source += '    ]\n}\n'
(ROOT / 'Sources/Models/StarterVocabulary.swift').write_text(source)
source = '// Generated by Scripts/GenerateVocabulary.py.\nimport Foundation\n\nenum SynonymCatalog {\n    static let Families: [SynonymFamily] = [\n'
for f in families:
    source += f'        SynonymFamily(Code: {quoted(f["Code"])}, Head: {quoted(f["Head"])}, Sense: {quoted(f["Sense"])}, Terms: [{", ".join(map(quoted, f["Terms"]))}]),\n'
source += '    ]\n    static let LegacyGroups: Set<String> = [' + ', '.join(map(quoted, sorted(legacy))) + ']\n}\n'
(ROOT / 'Sources/Models/SynonymCatalog.swift').write_text(source)
print(f'{len(rows)} source rows → {len(words)} words, {len(families)} reviewed families; all source meanings retained.')
